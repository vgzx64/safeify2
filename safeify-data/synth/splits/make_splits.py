"""Freeze the real held-out split for safeify-ai and safeify-data/synth.

Splits the REAL query corpus (vendors/SafeNet/testdata/, 474 .rs files) into
train / valid / test, stratified by (api, pattern_id), deterministically
(seed-pinned per file, no global shuffle state).

Design decisions (see splits/README.md):
  * vendors/SafeNet/knowledgebase/ stays OUT of the split: it is the gallery
    SafeNet retrieves against, never a training/eval query.
  * snippet-level 70/10/20 within each (api, pattern) stratum -> every API with
    >=3 usable files per pattern keeps representation in all three splits.
  * a file is 'usable' only if it has a pattern id AND a cached processed
    sequence (out/ast_json_real/gh/...), i.e. it survived extract_ast + the
    baseline preprocess -- the same gates gen/pairs.py applies. The 19 known
    syn-parse failures and pattern-less files (e.g. Rc::from_raw/pending.rs)
    are recorded as excluded, never silently dropped.

Outputs (all under splits/):
  train.txt valid.txt test.txt   one relative path per line (sorted)
  manifest.json                 every testdata file -> split/excluded + api,
                                pattern, kind, sha256 of its sequence
  stats.json                    counts, per-stratum table, leakage audit
  README.md                     method + numbers (regenerated by --write-readme)

Usage:  python splits/make_splits.py            (from research/synth/)
        python splits/make_splits.py --check    verify frozen files unchanged
"""

import argparse
import hashlib
import json
import os
import re
import sys

SYNTH_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SAFE_ROOT = os.path.join(SYNTH_ROOT, "..", "..", "vendors", "SafeNet")
TESTDATA = os.path.join(SAFE_ROOT, "testdata")
KB = os.path.join(SAFE_ROOT, "knowledgebase")
JSON_CACHE = os.path.join(SYNTH_ROOT, "out", "ast_json_real", "gh")
SPLITS_DIR = os.path.join(SYNTH_ROOT, "splits")

SEED = 1234
RATIOS = {"train": 0.7, "valid": 0.1, "test": 0.2}
SPLITS = ("train", "valid", "test")


def api_key(name):
    """Directory name -> canonical API key (pairs.py api_key + rstrip)."""
    return name.replace("(c)", "").strip()


def pattern_of(fname):
    m = re.match(r"^(\d+)-", fname)
    return int(m.group(1)) if m else None


def seed_for(*parts):
    """Deterministic 64-bit seed for a file (stable across runs/platforms)."""
    h = hashlib.sha256(("|".join(str(p) for p in parts)
                        + f"|{SEED}").encode("utf-8")).digest()
    return int.from_bytes(h[:8], "big")


def enumerate_testdata():
    """Every .rs under testdata/ -> record dicts (before usability check)."""
    recs = []
    for dirpath, _, files in os.walk(TESTDATA):
        for fname in sorted(files):
            if not fname.endswith(".rs"):
                continue
            rel = os.path.relpath(os.path.join(dirpath, fname), TESTDATA)
            rel = rel.replace(os.sep, "/")
            api_dir = os.path.relpath(dirpath, TESTDATA)
            recs.append({
                "rel_path": rel,
                "api": api_key(api_dir),
                "pattern_id": pattern_of(fname),
                "kind": "safe" if "-safe" in fname[:-3] else "unsafe",
            })
    return recs


def cached_json(rel_path):
    """Path of the cached processed sequence for a testdata-relative path."""
    return os.path.join(JSON_CACHE, *rel_path.split("/"))[:-3] + ".json"


def load_sequence(rel_path):
    path = cached_json(rel_path)
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def annotate_usability(recs):
    """Mark usable/excluded + attach sequence sha for usable files."""
    for rec in recs:
        if rec["pattern_id"] is None:
            rec.update(usable=False, excluded="no_pattern_id")
            continue
        seq = load_sequence(rec["rel_path"])
        if seq is None or not seq.split():
            rec.update(usable=False, excluded="no_cached_sequence")
            continue
        rec.update(usable=True, excluded=None,
                   ast_len=len(seq.split()),
                   seq_sha256=hashlib.sha256(seq.encode("utf-8")).hexdigest())
    return recs


def assign_split(cell_size, index):
    """Assign the index-th file of a stratum to train/valid/test (70/10/20).

    Guarantees: train >= 1, test >= 1 whenever cell_size >= 3; small cells
    stay deterministic and non-empty where meaningful.
    """
    if cell_size == 1:
        return "train"
    if cell_size == 2:
        return "train" if index == 0 else "test"
    n_train = max(1, round(cell_size * RATIOS["train"]))
    n_valid = max(1, round(cell_size * RATIOS["valid"]))
    n_test = max(1, round(cell_size * RATIOS["test"]))
    counts = {"train": n_train, "valid": n_valid, "test": n_test}
    # never exceed the cell: shave the largest buckets (keeping >= 1 each)
    while sum(counts.values()) > cell_size:
        biggest = max(counts, key=lambda k: (counts[k], k))
        if counts[biggest] <= 1:
            break
        counts[biggest] -= 1
    # never waste files: give the remainder to train
    while sum(counts.values()) < cell_size:
        counts["train"] += 1
    if index < counts["train"]:
        return "train"
    if index < counts["train"] + counts["valid"]:
        return "valid"
    return "test"


def split_records(recs):
    """Assign a split to every usable record (stratified, seeded).

    Stratification cell = (api, pattern_id), but files with an IDENTICAL
    processed sequence are grouped first and moved as one unit — otherwise a
    byte-duplicate (e.g. ptr::copy/4-13.rs vs ptr::copy/1-2(4-14).rs) could
    land in train and test simultaneously, which is exact leakage.
    """
    # group key: files sharing a processed sequence move as one unit
    units = {}
    for rec in recs:
        if not rec["usable"]:
            rec["split"] = None
            continue
        rec["_group"] = (rec["api"], rec["seq_sha256"])
        units.setdefault(rec["_group"], []).append(rec)

    cell_units = {}
    for group in units.values():
        counts = {}
        for rec in group:
            key = (rec["api"], rec["pattern_id"])
            counts[key] = counts.get(key, 0) + 1
        dominant = sorted(counts, key=lambda k: (-counts[k], k))[0]
        cell_units.setdefault(dominant, []).append(group)

    for cell, groups in sorted(cell_units.items(),
                               key=lambda kv: str(kv[0])):
        api, pattern = cell
        order = sorted(groups,
                       key=lambda g: (seed_for(api, pattern,
                                               sorted(r["rel_path"]
                                                      for r in g)[0]),
                                      sorted(r["rel_path"] for r in g)[0]))
        for i, group in enumerate(order):
            split = assign_split(len(order), i)
            for rec in group:
                rec["split"] = split
    return recs


def group_label_conflicts(recs):
    """Duplicate groups whose members disagree on (pattern_id, kind)."""
    groups = {}
    for rec in recs:
        if rec["usable"]:
            groups.setdefault((rec["api"], rec["seq_sha256"]),
                              []).append(rec)
    out = []
    for (api, sha), members in groups.items():
        if len(members) < 2:
            continue
        if len({m["pattern_id"] for m in members}) > 1:
            out.append({"api": api, "seq_sha256": sha[:16],
                        "files": [{"path": m["rel_path"],
                                   "pattern_id": m["pattern_id"],
                                   "split": m["split"]} for m in members]})
    return out



def leakage_audit(recs):
    """Exact-sequence overlap between splits (same API = real leakage)."""
    by_sha = {}
    for rec in recs:
        if rec["usable"]:
            by_sha.setdefault(rec["seq_sha256"], []).append(rec)
    same_api, cross_api = [], []
    for sha, group in by_sha.items():
        if len({g["split"] for g in group}) < 2:
            continue
        entry = {"seq_sha256": sha[:16],
                 "files": [{"split": g["split"], "path": g["rel_path"],
                            "api": g["api"]} for g in group]}
        if len({g["api"] for g in group}) == 1:
            same_api.append(entry)
        else:
            cross_api.append(entry)
    return {"same_api_overlap": same_api, "cross_api_overlap": cross_api}


def strat_table(recs):
    rows, cells = [], {}
    for rec in recs:
        if not rec["usable"]:
            continue
        key = (rec["api"], rec["pattern_id"])
        row = cells.setdefault(key, {"api": key[0], "pattern": key[1],
                                     "train": 0, "valid": 0, "test": 0,
                                     "total": 0})
        row[rec["split"]] += 1
        row["total"] += 1
    for key in sorted(cells, key=lambda k: (k[0], k[1])):
        rows.append(cells[key])
    return rows


def kb_pairs():
    """(api, pattern) pairs present in the knowledgebase gallery."""
    out = set()
    for dirpath, _, files in os.walk(KB):
        for fname in files:
            if not fname.endswith(".rs"):
                continue
            p = pattern_of(fname)
            if p is not None:
                out.add((api_key(os.path.relpath(dirpath, KB)), p))
    return out


def check_verdict_map(recs):
    """Every usable (api, pattern) must have a KB verdict; report strays."""
    with open(os.path.join(SPLITS_DIR, "kb_verdicts.json"),
              encoding="utf-8") as f:
        verdicts = json.load(f)["apis"]
    missing, covered = [], set()
    for rec in recs:
        if not rec["usable"]:
            continue
        if verdicts.get(rec["api"], {}).get(str(rec["pattern_id"])) is None:
            missing.append(f"{rec['api']}/p{rec['pattern_id']}")
        else:
            covered.add(f"{rec['api']}/p{rec['pattern_id']}")
    stray = [f"{api}/p{p}" for api, pats in verdicts.items()
             if not api.startswith("_") for p in pats
             if f"{api}/p{p}" not in covered]
    return {"missing_verdict": sorted(set(missing)),
            "verdict_without_testdata": sorted(stray)}


def render_readme(stats):
    stratum_rows = "\n".join(
        f"| {r['api']} | {r['pattern']} | {r['train']} | {r['valid']} | "
        f"{r['test']} | {r['total']} |" for r in stats["strata"])
    excluded = "\n".join(
        f"- `{e['rel_path']}` — {e['excluded']}"
        for e in stats["excluded"]) or "- (none)"
    return f"""# splits/ — frozen real held-out split (testdata queries)

Regenerate: `python splits/make_splits.py` (from `research/synth/`);
verify an untouched checkout: `python splits/make_splits.py --check`.

## What is split, and what is not

| corpus | role | split? |
|---|---|---|
| `vendors/SafeNet/knowledgebase/` ({stats['n_gallery']} .rs) | retrieval **gallery** (fixed) | no — never a query |
| `vendors/SafeNet/testdata/` ({stats['n_total']} .rs) | real **queries** | yes — 70/10/20 |
| `research/synth/out/snippets/` | synthetic training rows | no — never evaluated |

* stratified by **(api, pattern_id)**, seed {stats['seed']}, per-file stable
  seed (no global RNG) → byte-identical on re-run.
* only **usable** files get a split: a pattern id in the filename AND a cached
  sequence in `out/ast_json_real/gh/` (survived `extract_ast` + baseline
  preprocess). {stats['n_usable']} usable / {stats['n_total']} total,
  {len(stats['excluded'])} excluded:

{excluded}

## Sizes

| split | usable .rs | target |
|---|---|---|
| train | {stats['n_train']} | 70% |
| valid | {stats['n_valid']} | 10% |
| test  | {stats['n_test']} | 20% |

## Leakage audit (exact sequence sha256 across splits)

* same-API overlap (real leakage): **{len(stats['leakage']['same_api_overlap'])}**
* cross-API identical sequences (informational): {len(stats['leakage']['cross_api_overlap'])}
* duplicate groups with conflicting gold pattern ids: {len(stats['label_conflicts'])}
  (corpus defect, e.g. `ptr::copy/4-13.rs` is byte-identical to
  `ptr::copy/1-2(4-14).rs` — same sequence, two filenames, two pattern ids).
  These groups are kept together in ONE split (never split across), and every
  conflict is itemised in `stats.json → label_conflicts` for manual review.

## Per-stratum counts

| api | pattern | train | valid | test | total |
|---|---|---|---|---|---|
{stratum_rows}

## Evaluation protocol (enforced by `splits/eval_protocol.py`)

1. **Train** on shipped `train.csv` / `train_synth.csv` / `train_mixed.csv`
   (+`train_hard.csv`).
2. **Select** epochs/threshold on `valid` only.
3. **Report once** on `test`: pair metrics + per-pattern recall + FP rate on
   `verdict=N` (irreplaceable) — `python splits/eval_protocol.py --preds ...`
4. Never report a synthetic-measured number as a result
   (`notes/research/synthetic-data-theory.md`).

Gold verdicts per (api, pattern) live in `kb_verdicts.json`, transcribed from
`vendors/SafeNet/knowledgebase/README.md`.
"""


def write_outputs(recs, stats, write_readme):
    os.makedirs(SPLITS_DIR, exist_ok=True)
    for s in SPLITS:
        paths = sorted(r["rel_path"] for r in recs if r.get("split") == s)
        with open(os.path.join(SPLITS_DIR, f"{s}.txt"), "w",
                  encoding="utf-8") as f:
            f.write("\n".join(paths) + "\n")
        stats[f"n_{s}"] = len(paths)

    with open(os.path.join(SPLITS_DIR, "manifest.json"), "w",
              encoding="utf-8") as f:
        json.dump({"seed": SEED, "ratios": RATIOS,
                   "testdata_root": "vendors/SafeNet/testdata",
                   "files": recs}, f, indent=2, ensure_ascii=False)
    with open(os.path.join(SPLITS_DIR, "stats.json"), "w",
              encoding="utf-8") as f:
        json.dump(stats, f, indent=2, ensure_ascii=False)
    if write_readme:
        with open(os.path.join(SPLITS_DIR, "README.md"), "w",
                  encoding="utf-8") as f:
            f.write(render_readme(stats))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify frozen split files match a fresh run")
    ap.add_argument("--write-readme", action="store_true")
    args = ap.parse_args()

    recs = split_records(annotate_usability(enumerate_testdata()))
    recs.sort(key=lambda r: r["rel_path"])
    usable = [r for r in recs if r["usable"]]

    stats = {
        "seed": SEED,
        "ratios": RATIOS,
        "n_total": len(recs),
        "n_usable": len(usable),
        "n_gallery": sum(1 for d, _, fs in os.walk(KB)
                         for f in fs if f.endswith(".rs")),
        "excluded": [{"rel_path": r["rel_path"], "excluded": r["excluded"],
                      "api": r["api"], "pattern_id": r["pattern_id"]}
                     for r in recs if not r["usable"]],
        "strata": strat_table(recs),
        "leakage": leakage_audit(recs),
        "label_conflicts": group_label_conflicts(recs),
        "verdict_map": check_verdict_map(recs),
    }

    if args.check:
        ok = True
        for s in SPLITS:
            frozen = os.path.join(SPLITS_DIR, f"{s}.txt")
            fresh = sorted(r["rel_path"] for r in recs if r.get("split") == s)
            if not os.path.isfile(frozen):
                print(f"MISSING {frozen}")
                ok = False
                continue
            with open(frozen, encoding="utf-8") as f:
                have = [l.strip() for l in f if l.strip()]
            same = have == fresh
            print(f"{s}.txt {'OK' if same else 'DRIFT'} "
                  f"(frozen={len(have)} fresh={len(fresh)})")
            ok = ok and same
        print(f"leakage same_api="
              f"{len(stats['leakage']['same_api_overlap'])} "
              f"cross_api={len(stats['leakage']['cross_api_overlap'])}")
        sys.exit(0 if ok else 1)

    write_outputs(recs, stats, args.write_readme)
    print(f"splits: train={stats['n_train']} valid={stats['n_valid']} "
          f"test={stats['n_test']} usable={stats['n_usable']}/"
          f"{stats['n_total']} excluded={len(stats['excluded'])}")
    print(f"leakage: same_api={len(stats['leakage']['same_api_overlap'])} "
          f"cross_api={len(stats['leakage']['cross_api_overlap'])}")
    vm = stats["verdict_map"]
    if vm["missing_verdict"]:
        print("WARN missing verdicts:", vm["missing_verdict"])
    if vm["verdict_without_testdata"]:
        print("info verdict cells without testdata:",
              vm["verdict_without_testdata"])


if __name__ == "__main__":
    main()
