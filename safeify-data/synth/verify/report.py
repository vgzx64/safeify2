"""Generate out/report.md — dataset statistics + scientific framing."""

import json
import os
import subprocess
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "gen"))
from common import SYNTH_ROOT  # noqa: E402

BASELINE_CSV = os.path.join(SYNTH_ROOT, "..", "..", "vendors", "SafeNet",
                            "src", "model", "data", "baaaa", "train.csv")
OUT = os.path.join(SYNTH_ROOT, "out", "report.md")


def load_manifest():
    with open(os.path.join(SYNTH_ROOT, "out", "pairs_manifest.jsonl"),
              encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def table(rows, header):
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join(["---"] * len(header)) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(lines)


def collect():
    recs = load_manifest()
    base = pd.read_csv(BASELINE_CSV)
    base_len = base["text1"].str.split().str.len()

    n = len(recs)
    compile_ok = sum(1 for r in recs if r["verification"]["compile"])
    kept = [r for r in recs if r.get("ok")]
    dup = [r for r in recs if r.get("dropped")]
    lens = sorted(r["ast_len"] for r in recs if r.get("ast_len"))

    by_source = {}
    by_verdict = {}
    by_api_kind = {}
    for r in kept:
        by_source[r["source"]] = by_source.get(r["source"], 0) + 1
        by_verdict[r["verdict"]] = by_verdict.get(r["verdict"], 0) + 1
        k = f"{r['api']} / p{r['pattern_id']} / {r['kind']}"
        by_api_kind[k] = by_api_kind.get(k, 0) + 1

    csv_rows = []
    for name in ("train_synth", "train_real", "train_mixed", "train_hard"):
        df = pd.read_csv(os.path.join(SYNTH_ROOT, "out", f"{name}.csv"))
        vc = df["label"].value_counts()
        lens_t = df["text1"].str.split().str.len()
        csv_rows.append([name, len(df), int(vc.get(1, 0)), int(vc.get(-1, 0)),
                         int(lens_t.median()), int(lens_t.max())])

    # round-trip: real re-processed seqs found verbatim in shipped train.csv
    csv_text = open(BASELINE_CSV, encoding="utf-8").read()
    win = 8
    checked = matched = 0
    for corpus in ("kb", "gh"):
        root = os.path.join(SYNTH_ROOT, "out", "ast_json_real", corpus)
        for dirpath, _, files in os.walk(root):
            for fname in files:
                if not fname.endswith(".json"):
                    continue
                with open(os.path.join(dirpath, fname), encoding="utf-8") as jf:
                    seq = json.load(jf)
                toks = seq.split()
                if len(toks) < win:
                    continue
                checked += 1
                if any(" ".join(toks[i:i + win]) in csv_text
                       for i in range(len(toks) - win + 1)):
                    matched += 1

    failed_real = subprocess.run(
        [os.path.join(SYNTH_ROOT, "tools", "extract_ast", "target", "release",
                      "extract_ast"),
         os.path.join(SYNTH_ROOT, "..", "..", "vendors", "SafeNet", "testdata"),
         "/tmp/extract_recheck"],
        capture_output=True, text=True).stderr.strip().splitlines()
    return recs, n, compile_ok, kept, dup, lens, base_len, by_source, by_verdict, \
        by_api_kind, csv_rows, checked, matched, failed_real


def main():
    (recs, n, compile_ok, kept, dup, lens, base_len, by_source, by_verdict,
     by_api_kind, csv_rows, checked, matched, failed_real) = collect()
    win = 8  # round-trip window size used in collect()

    out = f"""# Synthetic dataset for SafeNet-style BERT/SNN training — report

Generated by `research/synth/` (strategies A+B, deterministic, no LLM).
Regenerate with `python build.py`.

## 1. Generation & verification

| metric | value |
|---|---|
| snippets generated | {n} |
| rustc compile pass | {compile_ok}/{n} |
| distinct sequences kept (after exact dedupe) | {len(kept)} |
| dropped as duplicates | {len(dup)} |
| ast_len p50 / p90 / max (synthetic) | {lens[len(lens)//2]} / {lens[int(len(lens)*0.9)]} / {max(lens)} |
| ast_len p50 / max (shipped baseline text1) | {int(base_len.median())} / {int(base_len.max())} |

Dedupe collapses grids that vary **only type names or identifier names**,
because SafeNet's preprocessing normalizes both to `varN` — a structural
property of the baseline representation (motivating the GNN vector). Context
wrappers (`mod synth_m1 {{...}}`) are what create genuinely distinct rows.

### Kept rows by strategy
{table(sorted(by_source.items()), ["source", "rows"])}

### Kept rows by verdict (label taxonomy)
{table(sorted(by_verdict.items()), ["verdict", "rows"])}

### Kept rows by (api, pattern, kind)
{table(sorted(by_api_kind.items()), ["api / pattern / kind", "rows"])}

## 2. Training pair CSVs (format-identical to shipped train.csv)

{table(csv_rows, ["file", "pairs", "label 1", "label -1", "len p50", "len max"])}

- `train_synth.csv` — synthetic-only pairs (ablation: *synthetic only*).
- `train_real.csv` — real (KB + train-split GitHub) within-API pairs (the
  clean *real-only* ablation; the shipped `vendors/SafeNet/.../train.csv`
  contains test/valid snippets and must not be used for a held-out result).
- `train_mixed.csv` — real (KB + train-split GitHub) + synthetic within-API
  pairs (the theory note's *train on synthetic + real* formula).
- `train_hard.csv` — cross-API negatives only (same pattern id across APIs =
  adversarial; others = easy). All label -1; combine with a positive file for
  a hard-negative curriculum.

All four files are built from `splits/train.txt` + KB only. Six train-split
files whose normalized sequence is byte-identical to a valid/test sequence are
dropped, and `splits/check_train_leakage.py` must print `OK` for every file
before training. `valid`/`test` are evaluation-only.

## 3. Pipeline identity vs the shipped baseline

Round-trip check: for every real KB/GitHub snippet re-processed through
`extract_ast` -> `pipe/preprocess`, does an {win}-token window of its computed
sequence appear **verbatim** in the shipped `train.csv`?

- snippets checked: {checked}
- with >=1 verbatim window: {matched} ({100.0 * matched / max(checked, 1):.1f}%)

A non-100% rate is expected: the committed `simplifyast.py` and the shipped
CSV were produced by slightly different script revisions (documented in
`pipe/preprocess.py`), and some GitHub sources were edited after CSV export.
The formatting conventions (`varN`, `*_token`, branch counts, literal known
idents) hold in both.

Real-corpus syn parse failures ({len(failed_real)}) are pre-existing sources;
they are skipped, not repaired:

```
{chr(10).join(failed_real[:25])}
```

## 4. Evaluation protocol (do NOT benchmark on synthetic)

Per `notes/research/synthetic-data-theory.md`:

1. **Real-only baseline**: train on `train_real.csv`, test on held-out real
   snippets (project-wise split of `testdata/`). Do not train on the shipped
   `vendors/SafeNet/.../train.csv`: it contains 25 test and 23 valid snippets.
2. **Synthetic-only**: train on `train_synth.csv`, test on the *same* real
   hold-out (diagnostic: synthetic alone must not win).
3. **Real + synthetic**: train on `train_mixed.csv`, test on the same hold-out.
4. **+ hard negatives**: add `train_hard.csv` rows to training.
5. Report per-pattern recall and the FP rate on `verdict=irreplaceable`
   snippets — the FP-reduction target of `notes/research/research-vectors.md`.

Never report a number measured on synthetic data as a result. The valid pair
set is 10 pairs (5 pos / 5 neg), so it is a weak selection signal; record that
limitation explicitly and prefer grouped CV on train for tuning.

## 5. Provenance

Every snippet is traceable through `out/pairs_manifest.jsonl`:
`source` (counterfactual_injection | template), `rule`/`family`, `variant`,
`contract`, `replaceability`, `verdict`, `verification`, `seq_sha256`,
`dropped`/`ok` flags.
"""
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"report: {OUT}")


if __name__ == "__main__":
    main()
